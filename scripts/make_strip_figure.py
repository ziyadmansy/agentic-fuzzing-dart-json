#!/usr/bin/env python3
"""Write paper/fig_rq2_strip.tex: per-run RQ2 divergence rate of every arm, as a dot strip plot.

Computes each run's rate with aggregate_rq2_runs.collect_run from the committed
artifacts, so the figure recomputes from the data:

    .venv/bin/python scripts/make_strip_figure.py
"""

from __future__ import annotations

import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from aggregate_rq2_runs import collect_run  # noqa: E402

WIDTH = 5.0  # cm of plot width for 0..50 %
HIGH = 50.0
ROW = 0.40  # cm between rows

# (label, arm directory, seeds); score-only is seeds 3-7 of rq2-loop-run01
# (seeds 0-2 ran the first, superseded prompt).
ARMS = [
    ("static baseline", "rq2-baseline-n5", None),
    ("score-only", "rq2-loop-run01", {3, 4, 5, 6, 7}),
    ("JSON allowed", "rq2-loop-json-allowed", None),
    ("categories", "rq2-loop-category-feedback", None),
    ("mutate source", "rq2-loop-mutate-source", None),
    ("gpt-4.1", "rq2-loop-gpt41-lenient", None),
    ("knowledge parity", "rq2-loop-knowledge-parity", None),
]


def rates(arm: str, seeds: set[int] | None) -> list[float]:
    values = []
    for run in sorted((ROOT / "artifacts" / "repeated" / arm).glob("run-*")):
        if seeds is not None and int(run.name.split("seed-")[1]) not in seeds:
            continue
        values.append(collect_run(run)["divergence_rate_over_total"])
    return values


def main() -> None:
    x = lambda value: value / HIGH * WIDTH  # noqa: E731
    out = [
        "% Generated by scripts/make_strip_figure.py from artifacts/repeated; do not edit.",
        "\\begin{tikzpicture}[font=\\footnotesize]",
    ]
    y = 0.0
    for label, arm, seeds in ARMS:
        values = rates(arm, seeds)
        mean = statistics.mean(values)
        out.append(f"\\node[anchor=east] at (-0.1,{y:.2f}) {{{label}}};")
        out.append(f"\\draw[black!12] (0,{y:.2f}) -- ({WIDTH},{y:.2f});")
        for value in values:
            out.append(f"\\fill[black!70] ({x(value):.3f},{y:.2f}) circle (1.5pt);")
        out.append(
            f"\\draw[black, line width=1.1pt] ({x(mean):.3f},{y - 0.15:.2f}) -- ({x(mean):.3f},{y + 0.15:.2f});"
        )
        out.append(f"\\node[anchor=west, black!70] at ({WIDTH + 0.08},{y:.2f}) {{{mean:.2f}}};")
        bottom = y
        y -= ROW
    axis = bottom - 0.32
    out.append(f"\\draw[black!60] (0,{axis:.2f}) -- ({WIDTH},{axis:.2f});")
    for tick in range(0, 51, 10):
        out.append(f"\\draw[black!60] ({x(tick):.3f},{axis:.2f}) -- ({x(tick):.3f},{axis - 0.07:.2f});")
        out.append(f"\\node[anchor=north, black!70] at ({x(tick):.3f},{axis - 0.07:.2f}) {{{tick}}};")
    out.append(
        f"\\node[anchor=north] at ({WIDTH / 2:.2f},{axis - 0.38:.2f}) "
        "{divergent documents (\\% of all generated)};"
    )
    out.append(f"\\node[anchor=south west, black!70] at ({WIDTH + 0.02},0.12) {{mean}};")
    out.append("\\end{tikzpicture}")
    (ROOT / "paper" / "fig_rq2_strip.tex").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
